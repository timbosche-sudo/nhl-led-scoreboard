/**
 * Hand-designed bitmap fonts for LED matrices. Every glyph is pixel art: there
 * is no anti-aliasing, so what you see in the simulator is exactly what the
 * hardware will light.
 */
export interface Glyph {
  width: number;
  /** rows[y] is a bitmask; bit (width-1-x) set means pixel x is lit. */
  rows: number[];
}

export interface BitmapFont {
  name: string;
  height: number;
  /** Default spacing between glyphs, in pixels. */
  spacing: number;
  glyphs: Record<string, Glyph>;
}

function fromRows(width: number, table: Record<string, number[]>, widths: Record<string, number> = {}): Record<string, Glyph> {
  const out: Record<string, Glyph> = {};
  for (const [ch, rows] of Object.entries(table)) out[ch] = { width: widths[ch] ?? width, rows };
  return out;
}

function fromArt(art: Record<string, string[]>): Record<string, Glyph> {
  const out: Record<string, Glyph> = {};
  for (const [ch, lines] of Object.entries(art)) {
    const width = lines[0].length;
    out[ch] = { width, rows: lines.map((l) => parseInt(l.replace(/[^#]/g, '0').replace(/#/g, '1'), 2)) };
  }
  return out;
}

